import { z } from 'zod';
import { requestBytes, requestJson } from '../http.ts';
import { ProviderError, type VideoGenerator, type VideoRequest, type VideoStatus } from '../types.ts';

const BASE_URL = 'https://generativelanguage.googleapis.com/v1beta';

const StartResponse = z.object({ name: z.string().min(1) });

const OperationResponse = z.object({
  name: z.string().optional(),
  done: z.boolean().optional(),
  error: z.object({ code: z.number().optional(), message: z.string().optional() }).optional(),
  response: z
    .object({
      generateVideoResponse: z
        .object({
          generatedSamples: z.array(z.object({ video: z.object({ uri: z.string() }).optional() })).optional(),
          raiMediaFilteredCount: z.number().optional(),
          raiMediaFilteredReasons: z.array(z.string()).optional(),
        })
        .optional(),
    })
    .optional(),
});

/**
 * Veo image-to-video through the Gemini API (predictLongRunning + operation polling).
 * Docs: https://ai.google.dev/gemini-api/docs/veo (checked 2026-10-12).
 * Audio is always generated by these models; we keep the file as-is and play it muted.
 * Generated videos are deleted from Google's side after 2 days, so download promptly.
 */
export class VeoVideoGenerator implements VideoGenerator {
  readonly provider = 'google';
  readonly model: string;
  readonly costPerSecondUsd: number;
  readonly apiKey: string;

  constructor(opts: { apiKey: string; model: string; costPerSecondUsd: number }) {
    this.apiKey = opts.apiKey;
    this.model = opts.model;
    this.costPerSecondUsd = opts.costPerSecondUsd;
  }

  estimateCostUsd(durationSeconds: number): number {
    return durationSeconds * this.costPerSecondUsd;
  }

  async start(req: VideoRequest): Promise<{ operationId: string }> {
    if (req.resolution === '1080p' && req.durationSeconds !== 8) {
      throw new ProviderError('Veo only renders 1080p at 8 seconds');
    }
    const frame = (img: { bytes: Buffer; mimeType: string }) => ({
      inlineData: { mimeType: img.mimeType, data: img.bytes.toString('base64') },
    });
    const json = await requestJson(`${BASE_URL}/models/${this.model}:predictLongRunning`, {
      method: 'POST',
      headers: { 'x-goog-api-key': this.apiKey },
      body: {
        instances: [
          {
            prompt: req.prompt,
            image: frame(req.firstFrame),
            ...(req.lastFrame ? { lastFrame: frame(req.lastFrame) } : {}),
          },
        ],
        parameters: {
          aspectRatio: '16:9',
          resolution: req.resolution,
          // The docs list durations as strings; proto JSON accepts a string for either type.
          durationSeconds: String(req.durationSeconds),
          personGeneration: 'allow_adult',
        },
      },
      // Not retried: a retry after a timeout could start (and bill) a second generation.
      retries: 0,
      timeoutMs: 120_000,
    });
    const parsed = StartResponse.safeParse(json);
    if (!parsed.success) throw new ProviderError(`Unexpected Veo start response: ${JSON.stringify(json).slice(0, 400)}`);
    return { operationId: parsed.data.name };
  }

  async check(operationId: string): Promise<VideoStatus> {
    const json = await requestJson(`${BASE_URL}/${operationId}`, {
      headers: { 'x-goog-api-key': this.apiKey },
      timeoutMs: 30_000,
    });
    const parsed = OperationResponse.safeParse(json);
    if (!parsed.success) throw new ProviderError(`Unexpected Veo operation response: ${JSON.stringify(json).slice(0, 400)}`);
    const op = parsed.data;
    if (!op.done) return { state: 'running' };
    if (op.error) return { state: 'failed', error: op.error.message ?? `Veo error code ${op.error.code}` };
    const result = op.response?.generateVideoResponse;
    const uri = result?.generatedSamples?.[0]?.video?.uri;
    if (uri) return { state: 'succeeded', videoRef: uri };
    const reasons = result?.raiMediaFilteredReasons?.join('; ');
    return { state: 'failed', error: reasons ? `Blocked by Veo safety filter: ${reasons}` : 'Veo finished without a video' };
  }

  download(videoRef: string): Promise<Buffer> {
    return requestBytes(videoRef, { headers: { 'x-goog-api-key': this.apiKey }, timeoutMs: 300_000 });
  }
}
